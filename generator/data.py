def jalali_date(rng: random.Random, y: int, m: int) -> str:
    return f"{y}/{m:02d}/{rng.randint(1, JALALI_MONTH_DAYS[m - 1]):02d}"


def sha256_file(path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()

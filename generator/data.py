def _digits(rng: random.Random, n: int) -> str:
    return "".join(str(rng.randint(0, 9)) for _ in range(n))


def make_national_code(rng: random.Random) -> str:
    while True:
        base = _digits(rng, 9)
        if len(set(base)) == 1:
            continue
        s = sum(int(base[i]) * (10 - i) for i in range(9))
        r = s % 11
        return base + str(r if r < 2 else 11 - r)


def make_legal_id(rng: random.Random) -> str:
    base = [int(x) for x in _digits(rng, 10)]
    coef = [29, 27, 23, 19, 17, 29, 27, 23, 19, 17]
    s = sum((base[i] + base[9] + 2) * coef[i] for i in range(10))
    r = s % 11
    return "".join(map(str, base)) + str(0 if r == 10 else r)


